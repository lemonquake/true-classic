@app_commands.guild_only()
async def edit_bot_message(interaction: discord.Interaction, message: discord.Message):
    if not interaction.guild:
        await interaction.response.send_message("This can only be used inside a server.", ephemeral=True)
        return

    if not has_authorized_role(interaction.user):
        await interaction.response.send_message(
            embed=embed_builder.error_embed("Permission Denied", "You do not have permission to edit the bot's messages."),
            ephemeral=True
        )
        return

    if message.author.id != interaction.client.user.id:
        await interaction.response.send_message(
            embed=embed_builder.error_embed(
                "Not My Message",
                f"Discord only lets a bot edit messages it posted itself, and this one is from "
                f"{message.author.mention}.\n\nTo compose something new, use **Embed Editor** on the Mod Panel."
            ),
            ephemeral=True
        )
        return

    session = MessageEditSession(message)
    hub_view = MessageEditHubView(session)

    print(f"[Message Editor] {interaction.user} opened the editor for message {message.id} in #{getattr(message.channel, 'name', message.channel.id)}")
    await interaction.response.send_message(
        embeds=hub_view.get_hub_embeds(),
        view=hub_view,
        ephemeral=True
    )


class MessageEditorCog(commands.Cog):
    def __init__(self, bot):
        self.bot = bot


async def setup(bot):
    await bot.add_cog(MessageEditorCog(bot))

    # A stale entry can linger if a previous load half-failed, so clear before adding.
    bot.tree.remove_command(CONTEXT_MENU_NAME, type=discord.AppCommandType.message)
    bot.tree.add_command(app_commands.ContextMenu(name=CONTEXT_MENU_NAME, callback=edit_bot_message))
    # Logged without the emoji: a cp1252 Windows console raises UnicodeEncodeError on it,
    # which would abort the whole extension load.
    print("[System] Registered message context menu: Edit Bot Message")


async def teardown(bot):
    # Hot-reload calls teardown then setup; without this the re-add raises
    # CommandAlreadyRegistered and the module fails to reload.
    bot.tree.remove_command(CONTEXT_MENU_NAME, type=discord.AppCommandType.message)
