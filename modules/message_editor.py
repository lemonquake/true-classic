CONTEXT_MENU_NAME = "✏️ Edit Bot Message"
MAX_EMBEDS = 10


class SecuredView(View):
    async def interaction_check(self, interaction: discord.Interaction) -> bool:
        if not has_authorized_role(interaction.user):
            await interaction.response.send_message(
                embed=embed_builder.error_embed(
                    "Permission Denied",
                    "You do not have the required permissions to use the Message Editor."
                ),
                ephemeral=True
            )
            return False
        return True


def has_authorized_role(user) -> bool:
    roles = getattr(user, "roles", None)
    if not roles:
        return False
    user_roles = {role.id for role in roles}
    return any(role_id in user_roles for role_id in config.AUTHORIZED_ROLES)


