class MessageEditHubView(SecuredView):
    def __init__(self, session: MessageEditSession):
        super().__init__(timeout=600)
        self.session = session
        self.create_dynamic_buttons()

    # -- Structure ----------------------------------------------------------

    def create_dynamic_buttons(self):
        # Rows 0 and 1 hold one selector per embed (5 per row, 10 embeds max).
        for idx in range(len(self.session.embeds)):
            label = f"E{idx+1} ✏️" if idx == self.session.current_index else f"E{idx+1}"
            style = ButtonStyle.blurple if idx == self.session.current_index else ButtonStyle.grey
            row = 0 if idx < 5 else 1

            btn = Button(label=label, style=style, row=row, custom_id=f"msg_edit_sel_{idx}")
            btn.callback = self.make_select_callback(idx)
            self.add_item(btn)

        jump_btn = Button(label="🔗 Jump to Message", style=ButtonStyle.link, url=self.session.message.jump_url, row=4)
        self.add_item(jump_btn)

    def make_select_callback(self, idx):
        async def callback(interaction: discord.Interaction):
            self.session.current_index = idx
            edit_view = EditEmbedView(self.session, self)
            await interaction.response.edit_message(
                embeds=[self.session.get_current_embed().to_discord_embed()],
                view=edit_view
            )
        return callback

    def rebuild(self):
        return MessageEditHubView(self.session)

    # -- Rendering ----------------------------------------------------------

    def get_hub_embed(self) -> discord.Embed:
        message = self.session.message
        content, embeds = self.session.build_payload()

        text_preview = "—"
        if content:
            text_preview = content if len(content) <= 200 else content[:197] + "..."

        embeds_summary = []
        for idx, e in enumerate(self.session.embeds):
            title = e.title or e.description or "(blank)"
            if len(title) > 60:
                title = title[:57] + "..."
            flag = " *(empty — will be dropped)*" if e.is_empty() else ""
            embeds_summary.append(f"Embed #{idx+1:02d}: {title}{flag}")

        hub = embed_builder.base_embed(
            title="✏️ Message Editor",
            description=(
                f"Editing a live message in {message.channel.mention} "
                f"(`{message.id}`).\n"
                "Use the **E#** buttons for the same controls as the Embed Editor. "
                "Nothing changes on the real message until you press **💾 Save Changes**."
            ),
            color=embed_builder.COLOR_INFO,
            footer_text=f"{embed_builder.BOT_NAME} • Message Editor"
        )
        hub.add_field(name="Message Text", value=text_preview, inline=False)
        hub.add_field(name="Editable Embeds", value=str(len(embeds)), inline=True)
        hub.add_field(name="Attachments", value=str(len(message.attachments)) + " (kept as-is)", inline=True)
        hub.add_field(name="Embeds List", value="\n".join(embeds_summary) or "—", inline=False)

        if self.session.skipped_auto_embeds:
            hub.add_field(
                name="Note",
                value=(
                    f"{self.session.skipped_auto_embeds} auto-generated preview embed(s) "
                    "(link/media unfurls) are not editable and were left out."
                ),
                inline=False
            )
        if self.session.status_line:
            hub.add_field(name="Status", value=self.session.status_line, inline=False)

        return hub

    def get_hub_embeds(self) -> list:
        # Hub summary plus a live preview of what will be written back.
        # A message carries at most 10 embeds, so cap the previews at 9.
        _, previews = self.session.build_payload()
        return [self.get_hub_embed()] + previews[:9]

    async def refresh_hub(self, interaction: discord.Interaction, defer=True):
        new_view = self.rebuild()
        if interaction.is_expired():
            return
        if interaction.response.is_done():
            # Reached after a defer() on a button press; edits the ephemeral hub in place.
            await interaction.edit_original_response(
                embeds=new_view.get_hub_embeds(),
                view=new_view
            )
        else:
            await interaction.response.edit_message(
                embeds=new_view.get_hub_embeds(),
                view=new_view
            )

    # -- Buttons ------------------------------------------------------------

    @discord.ui.button(label="📝 Message Text", style=ButtonStyle.grey, row=2)
    async def edit_message_text(self, interaction: discord.Interaction, button: Button):
        modal = MessageTextModal(self.session, self.refresh_hub)
        await interaction.response.send_modal(modal)

    @discord.ui.button(label="➕ Add Embed", style=ButtonStyle.green, row=2)
    async def add_embed(self, interaction: discord.Interaction, button: Button):
        if len(self.session.embeds) >= MAX_EMBEDS:
            await interaction.response.send_message(
                embed=embed_builder.error_embed("Limit Reached", f"A message can hold a maximum of {MAX_EMBEDS} embeds."),
                ephemeral=True
            )
            return

        self.session.embeds.append(EmbedState())
        self.session.current_index = len(self.session.embeds) - 1
        self.session.status_line = None
        print(f"[Message Editor] Added blank Embed #{len(self.session.embeds)} to message {self.session.message.id}")
        await self.refresh_hub(interaction)

    @discord.ui.button(label="🔄 Reload from Message", style=ButtonStyle.grey, row=2)
    async def reload_from_message(self, interaction: discord.Interaction, button: Button):
        await interaction.response.defer()
        try:
            fresh = await self.session.message.channel.fetch_message(self.session.message.id)
        except discord.NotFound:
            self.session.status_line = "🔴 That message no longer exists — it was deleted."
            await self.refresh_hub(interaction)
            return
        except discord.HTTPException as e:
            self.session.status_line = f"🔴 Could not re-fetch the message: `{e}`"
            await self.refresh_hub(interaction)
            return

        self.session.load_from_message(fresh)
        self.session.status_line = "🔄 Reloaded from the live message — unsaved edits were discarded."
        print(f"[Message Editor] Reloaded state from message {fresh.id}")
        await self.refresh_hub(interaction)

    @discord.ui.button(label="💬 Syntax Guide", style=ButtonStyle.grey, row=3)
    async def syntax_guide(self, interaction: discord.Interaction, button: Button):
        guide = (
            "**Discord Markdown Guide:**\n"
            "• *Italics*: `*text*` or `_text_`\n"
            "• **Bold**: `**text**`\n"
            "• ***Bold Italics***: `***text***`\n"
            "• __Underline__: `__text__`\n"
            "• ~~Strikethrough~~: `~~text~~`\n"
            "• Code Block: \\`\\`\\`text\\`\\`\\`\n"
            "• Inline Code: \\`text\\`\n"
            "• Mentions: `<@user_id>`, `<@&role_id>`, `<#channel_id>`\n"
            "• Custom Links: `[label](url)` (Only works inside Embed Descriptions or Fields)"
        )
        await interaction.response.send_message(guide, ephemeral=True)

    @discord.ui.button(label="💾 Save Changes", style=ButtonStyle.danger, row=3)
    async def save_changes(self, interaction: discord.Interaction, button: Button):
        content, embeds = self.session.build_payload()

        if content is None and not embeds:
            await interaction.response.send_message(
                embed=embed_builder.error_embed(
                    "Nothing to Save",
                    "A message cannot be blank. Add message text or fill in at least one embed."
                ),
                ephemeral=True
            )
            return

        await interaction.response.defer()
        try:
            updated = await self.session.message.edit(content=content, embeds=embeds)
            self.session.message = updated
            self.session.status_line = f"🟢 Saved. The message in {updated.channel.mention} is now live with these changes."
            print(f"[Message Editor] {interaction.user} saved edits to message {updated.id} in #{getattr(updated.channel, 'name', updated.channel.id)}")
        except discord.NotFound:
            self.session.status_line = "🔴 That message no longer exists — it was deleted."
            print(f"[Message Editor] Save failed: message {self.session.message.id} not found")
        except discord.Forbidden:
            self.session.status_line = "🔴 Missing permissions to edit that message."
            print(f"[Message Editor] Save failed: forbidden on message {self.session.message.id}")
        except discord.HTTPException as e:
            self.session.status_line = f"🔴 Discord rejected the edit: `{e}`"
            print(f"[Message Editor] Save failed on message {self.session.message.id}: {e}")

        await self.refresh_hub(interaction)

    @discord.ui.button(label="❌ Close Editor", style=ButtonStyle.secondary, row=3)
    async def close_editor(self, interaction: discord.Interaction, button: Button):
        await interaction.response.edit_message(
            embeds=[embed_builder.info_embed("Message Editor Closed", "No further changes will be applied.")],
            view=None
        )


