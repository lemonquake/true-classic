class MessageEditSession(EditorSession):
    """An EditorSession bound to a message that already exists in the server."""

    def __init__(self, message: discord.Message):
        super().__init__()
        self.message = message
        self.status_line = None
        self.load_from_message(message)

    def load_from_message(self, message: discord.Message):
        self.message = message
        self.global_text = message.content or None

        # Only "rich" embeds are author-controlled. Link previews and media
        # unfurls are generated by Discord and cannot be edited or re-sent.
        self.embeds = [
            EmbedState.from_discord_embed(e)
            for e in message.embeds
            if e.type == "rich"
        ]
        self.skipped_auto_embeds = len(message.embeds) - len(self.embeds)

        if not self.embeds:
            self.embeds = [EmbedState()]
        self.current_index = 0

    def build_payload(self):
        """(content, embeds) exactly as they will be written to the message."""
        embeds = [e.to_discord_embed() for e in self.embeds if not e.is_empty()]
        return (self.global_text or None), embeds


